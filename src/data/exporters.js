export function exportReport(kind, data) {
  const { workers, evidence, cases } = data;
  let title = "";
  let body = "";
  const statusCell = (v) => `<td class="${v === "Pass" || (v || "").includes("100%") ? "ok" : v === "N/A" ? "" : "risk"}">${v}</td>`;

  if (kind === "healthcare") {
    title = "Healthcare Joint Commission audit pack";
    const rows = workers.filter((w) => w.hc !== "N/A");
    body = `<h1>${title}</h1><p class="sub">License and credential coverage for ${rows.length} clinical workers</p>
    <table><tr><th>Worker</th><th>Role</th><th>Facility</th><th>Credentials</th><th>Overall</th></tr>
    ${rows.map((w) => `<tr><td>${w.name}</td><td>${w.role}</td><td>${w.facility}</td>${statusCell(w.hc)}${statusCell(w.overall)}</tr>`).join("")}</table>
    <h3>Verified evidence</h3><table><tr><th>Document</th><th>Worker</th><th>Number</th><th>Expiry</th><th>Status</th></tr>
    ${evidence.filter((e) => e.rule.startsWith("CTRL-HC")).map((e) => `<tr><td>${e.doc}</td><td>${e.worker}</td><td>${e.docNo}</td><td>${e.expiry}</td><td class="ok">${e.status}</td></tr>`).join("")}</table>`;
  } else if (kind === "i9") {
    title = "Onboarding & I-9 verification audit";
    body = `<h1>${title}</h1><p class="sub">Onboarding acknowledgments and I-9 status for ${workers.length} workers</p>
    <table><tr><th>Worker</th><th>Role</th><th>Onboarding</th><th>Immigration / I-9</th></tr>
    ${workers.map((w) => `<tr><td>${w.name}</td><td>${w.role}</td>${statusCell(w.onboard)}${statusCell(w.imm)}</tr>`).join("")}</table>
    <h3>Open onboarding & immigration cases</h3><table><tr><th>Case</th><th>Worker</th><th>Gap</th><th>Due</th></tr>
    ${cases.filter((c) => ["Onboarding", "Immigration"].includes(c.pack)).map((c) => `<tr><td>${c.id}</td><td>${c.worker}</td><td>${c.gap}</td><td>${c.due}</td></tr>`).join("") || "<tr><td colspan=4>None</td></tr>"}</table>`;
  } else {
    title = "Tax & state withholding summary";
    body = `<h1>${title}</h1><p class="sub">Payroll and tax compliance for ${workers.length} workers</p>
    <table><tr><th>Worker</th><th>Facility</th><th>Payroll / tax</th></tr>
    ${workers.map((w) => `<tr><td>${w.name}</td><td>${w.facility}</td>${statusCell(w.tax)}</tr>`).join("")}</table>`;
  }
  download(`aegis-${kind}-report.html`, htmlShell(title, body), "text/html");
}
