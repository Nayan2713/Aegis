// Client-side export helpers (no backend needed)

function download(filename, content, mime) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 500);
}

const esc = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;

export function toCSV(rows, columns) {
  const head = columns.map((c) => esc(c.label)).join(",");
  const body = rows.map((r) => columns.map((c) => esc(typeof c.get === "function" ? c.get(r) : r[c.key])).join(",")).join("\n");
  return `${head}\n${body}`;
}

export function exportAuditLog(logs) {
  const csv = toCSV(logs, [
    { label: "Timestamp", key: "time" },
    { label: "Event type", key: "type" },
    { label: "Subject", key: "subject" },
    { label: "Action", key: "action" },
    { label: "Actor", key: "actor" },
    { label: "Proof", key: "proof" },
  ]);
  download(`aegis-audit-log-${Date.now()}.csv`, csv, "text/csv");
}

